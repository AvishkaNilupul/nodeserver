const mongoose = require('mongoose');
const schema = new mongoose.Schema({
  localId: {type:String,required:true,unique:true},
  loginKey: {type:String,required:true,unique:true},
  accountName: {type:String,required:true},
  password: {type:String,required:true,select:false},
  email: {type:String,required:true,select:false},
  birthDate: {type:String,default:'',select:false},
  requestedCountry: {type:String,default:null},
  proxyCountry: {type:String,default:null},
  expectedShard: {type:String,default:null},
  country: {type:String,default:null},
  shard: {type:String,enum:['NA','EU','AP','LATAM','BR','KR',null],default:null},
  regionCheckedAt: {type:Date,default:null},
  regionEvidence: {type:String,default:'',maxlength:500},
  riotId: {type:String,default:'',maxlength:100},
  puuid: {type:String,default:'',maxlength:100},
  emailVerified: {type:Boolean,default:false},
  loginVerifiedAt: {type:Date,default:null},
  level: {type:Number,default:null,min:0,max:1000},
  rank: {type:String,default:'Unknown',maxlength:40},
  skinCount: {type:Number,default:null,min:0},
  agentCount: {type:Number,default:null,min:0},
  stage: {type:String,enum:['signup_pending','stock','listing','listed','sold','problem'],default:'signup_pending',index:true},
  signedUpAt: {type:Date,default:null},
  importedAt: {type:Date,default:Date.now},
  notes: {type:String,default:'',maxlength:2000},
  listingId: {type:String,default:''},
  listingUrl: {type:String,default:''},
  priceUsd: {type:Number,default:null},
  soldAt: {type:Date,default:null},
}, {timestamps:true});
module.exports = mongoose.models.ValorantAccount || mongoose.model('ValorantAccount',schema);
